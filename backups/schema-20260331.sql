          updated_at = NOW()
      WHERE id = v_user_id;

      -- Logger la transaction
      INSERT INTO loyalty_euro_transactions (user_id, type, amount, description, created_at)
      VALUES (v_user_id, 'order_cashback', v_cashback, 
              format('Cashback 2%% commande %s', NEW.order_number), NOW());
    END IF;
  END IF;
  RETURN NEW;
EXCEPTION
  WHEN OTHERS THEN
    RAISE WARNING '[cashback] Erreur order %: %', NEW.id, SQLERRM;
    RETURN NEW;
END;
