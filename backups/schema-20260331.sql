CREATE OR REPLACE FUNCTION "public"."restore_order_stock"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE item RECORD;
BEGIN
  IF NEW.status = 'cancelled' AND OLD.status != 'cancelled' THEN
    FOR item IN SELECT oi.product_id, oi.quantity, oi.variation_data FROM order_items oi WHERE oi.order_id = NEW.id
    LOOP
      UPDATE products SET stock_quantity = COALESCE(stock_quantity, 0) + item.quantity, stock_status = 'instock' WHERE id = item.product_id::uuid AND manage_stock = true;
      IF item.variation_data IS NOT NULL AND item.variation_data->>'variation_id' IS NOT NULL THEN
        UPDATE product_variations SET stock_quantity = COALESCE(stock_quantity, 0) + item.quantity WHERE id = (item.variation_data->>'variation_id')::uuid;
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN RAISE WARNING 'Erreur restore_order_stock: %', SQLERRM; RETURN NEW;
END; $$;


