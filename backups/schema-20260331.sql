CREATE OR REPLACE VIEW "public"."v_product_tags" AS
 WITH "raw_pairs" AS (
         SELECT "p"."id" AS "product_id",
            "jsonb_each"."key",
            "jsonb_each"."value"
           FROM "public"."products" "p",
            LATERAL "jsonb_each"(
                CASE
                    WHEN ("jsonb_typeof"("p"."attributes") = 'object'::"text") THEN "p"."attributes"
                    ELSE '{}'::"jsonb"
                END) "jsonb_each"("key", "value")
        UNION ALL
         SELECT "v"."product_id",
            "jsonb_each"."key",
            "jsonb_each"."value"
           FROM "public"."product_variations" "v",
            LATERAL "jsonb_each"(
                CASE
                    WHEN ("jsonb_typeof"("v"."attributes") = 'object'::"text") THEN "v"."attributes"
                    ELSE '{}'::"jsonb"
                END) "jsonb_each"("key", "value")
        ), "flattened_data" AS (
         SELECT "rp"."product_id",
            "rp"."key" AS "attr_key",
            "expansion"."val_expanded" AS "term_val"
           FROM ("raw_pairs" "rp"
             CROSS JOIN LATERAL ( SELECT "jsonb_array_elements_text"("rp"."value") AS "val_expanded"
                  WHERE ("jsonb_typeof"("rp"."value") = 'array'::"text")
                UNION ALL
                 SELECT ("rp"."value" ->> 0) AS "val_expanded"
                  WHERE ("jsonb_typeof"("rp"."value") <> 'array'::"text")) "expansion")
        )
 SELECT DISTINCT "fd"."product_id",
    "lower"(TRIM(BOTH FROM COALESCE("a"."name", "fd"."attr_key"))) AS "attribute_name",
    "lower"(TRIM(BOTH FROM COALESCE("t"."name", "fd"."term_val"))) AS "term_name",
    COALESCE("t"."name", "fd"."term_val") AS "original_term_name"
   FROM (("flattened_data" "fd"
     LEFT JOIN "public"."product_attribute_terms" "t" ON (((("t"."id")::"text" = "fd"."term_val") OR ("t"."name" = "fd"."term_val"))))
     LEFT JOIN "public"."product_attributes" "a" ON (((("a"."id")::"text" = "fd"."attr_key") OR ("a"."slug" = "fd"."attr_key") OR ("a"."name" = "fd"."attr_key"))));


ALTER VIEW "public"."v_product_tags" OWNER TO "postgres";


