CREATE OR REPLACE VIEW "public"."product_filter_radar" AS
 WITH "raw_data" AS (
         SELECT "products"."id" AS "product_id",
            ("jsonb_each_text"(
                CASE
                    WHEN ("jsonb_typeof"("products"."attributes") = 'object'::"text") THEN "products"."attributes"
                    ELSE '{}'::"jsonb"
                END))."key" AS "key",
            ("jsonb_each_text"(
                CASE
                    WHEN ("jsonb_typeof"("products"."attributes") = 'object'::"text") THEN "products"."attributes"
                    ELSE '{}'::"jsonb"
                END))."value" AS "value"
           FROM "public"."products"
        UNION ALL
         SELECT "product_variations"."product_id",
            ("jsonb_each_text"(
                CASE
                    WHEN ("jsonb_typeof"("product_variations"."attributes") = 'object'::"text") THEN "product_variations"."attributes"
                    ELSE '{}'::"jsonb"
                END))."key" AS "key",
            ("jsonb_each_text"(
                CASE
                    WHEN ("jsonb_typeof"("product_variations"."attributes") = 'object'::"text") THEN "product_variations"."attributes"
                    ELSE '{}'::"jsonb"
                END))."value" AS "value"
           FROM "public"."product_variations"
        )
 SELECT DISTINCT "rd"."product_id",
    "lower"(TRIM(BOTH FROM COALESCE("a"."name", "rd"."key"))) AS "attr_name",
    "lower"(TRIM(BOTH FROM COALESCE("t"."name", "rd"."value"))) AS "term_name",
    COALESCE("t"."name", "rd"."value") AS "original_term_name"
   FROM (("raw_data" "rd"
     LEFT JOIN "public"."product_attribute_terms" "t" ON ((("t"."id")::"text" = "rd"."value")))
     LEFT JOIN "public"."product_attributes" "a" ON (((("a"."id")::"text" = "rd"."key") OR ("a"."slug" = "rd"."key"))));


ALTER VIEW "public"."product_filter_radar" OWNER TO "postgres";


